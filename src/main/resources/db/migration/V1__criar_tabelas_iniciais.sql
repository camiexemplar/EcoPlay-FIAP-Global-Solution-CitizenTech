    ADD CONSTRAINT FK_ENTREGA_ECO_ON_CIDADAO FOREIGN KEY (cidadao_id) REFERENCES usuario_eco (id);

ALTER TABLE entrega_eco
    ADD CONSTRAINT FK_ENTREGA_ECO_ON_PONTO FOREIGN KEY (ponto_id) REFERENCES ponto_descarte_eco (id);

ALTER TABLE entrega_item_eco
    ADD CONSTRAINT FK_ENTREGA_ITEM_ECO_ON_ENTREGA FOREIGN KEY (entrega_id) REFERENCES entrega_eco (id);

ALTER TABLE entrega_item_eco
    ADD CONSTRAINT FK_ENTREGA_ITEM_ECO_ON_MATERIAL FOREIGN KEY (material_id) REFERENCES material_eco (id);

ALTER TABLE identificacao_eco
    ADD CONSTRAINT FK_IDENTIFICACAO_ECO_ON_MATERIAL FOREIGN KEY (material_id) REFERENCES material_eco (id);

ALTER TABLE identificacao_eco
    ADD CONSTRAINT FK_IDENTIFICACAO_ECO_ON_USUARIO FOREIGN KEY (usuario_id) REFERENCES usuario_eco (id);

ALTER TABLE ponto_descarte_eco
    ADD CONSTRAINT FK_PONTO_DESCARTE_ECO_ON_COOPERATIVA FOREIGN KEY (cooperativa_id) REFERENCES usuario_eco (id);

