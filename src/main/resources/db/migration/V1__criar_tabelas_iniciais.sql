CREATE SEQUENCE material_eco_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE entrega_eco
(
    id            NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    cidadao_id    NUMBER(38, 0)                                  NOT NULL,
    ponto_id      NUMBER(38, 0)                                  NOT NULL,
    data_prevista date                                           NOT NULL,
    status        VARCHAR2(20)                                   NOT NULL,
    motivo_recusa VARCHAR2(30),
    observacao    VARCHAR2(500),
    criado_em     date                                           NOT NULL,
    CONSTRAINT pk_entrega_eco PRIMARY KEY (id)
);

CREATE TABLE entrega_item_eco
(
    id          NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    entrega_id  NUMBER(38, 0)                                  NOT NULL,
    material_id NUMBER(38, 0)                                  NOT NULL,
    peso_kg     DECIMAL(10, 3),
    CONSTRAINT pk_entrega_item_eco PRIMARY KEY (id)
);

CREATE TABLE identificacao_eco
(
    id                      NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id              NUMBER(38, 0)                                  NOT NULL,
    material_id             NUMBER(38, 0),
    confianca               DECIMAL(5, 4),
    confirmada_pelo_usuario NUMBER(1)                                      NOT NULL,
    criado_em               TIMESTAMP                                      NOT NULL,
    CONSTRAINT pk_identificacao_eco PRIMARY KEY (id)
);

CREATE TABLE material_eco
(
    id            NUMBER(38, 0) NOT NULL,
    nome          VARCHAR2(100) NOT NULL,
    categoria     VARCHAR2(30)  NOT NULL,
    reciclavel    NUMBER(1)     NOT NULL,
    como_preparar VARCHAR2(100),
    classe_modelo VARCHAR2(100),
    CONSTRAINT pk_material_eco PRIMARY KEY (id)
);

CREATE TABLE ponto_descarte_eco
(
    id             NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome           VARCHAR2(150)                                  NOT NULL,
    tipo           VARCHAR2(50)                                   NOT NULL,
    endereco       VARCHAR2(250)                                  NOT NULL,
    bairro         VARCHAR2(150)                                  NOT NULL,
    horario        VARCHAR2(150),
    cooperativa_id NUMBER(38, 0),
    CONSTRAINT pk_ponto_descarte_eco PRIMARY KEY (id)
);

CREATE TABLE ponto_material
(
    material_id NUMBER(38, 0) NOT NULL,
    ponto_id    NUMBER(38, 0) NOT NULL,
    CONSTRAINT pk_ponto_material PRIMARY KEY (material_id, ponto_id)
);

CREATE TABLE usuario_eco
(
    id            NUMBER(38, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome          VARCHAR2(255)                                  NOT NULL,
    email         VARCHAR2(255)                                  NOT NULL,
    senha_hash    VARCHAR2(255)                                  NOT NULL,
    role          VARCHAR2(20)                                   NOT NULL,
    bairro        VARCHAR2(100),
    data_cadastro TIMESTAMP                                      NOT NULL,
    CONSTRAINT pk_usuario_eco PRIMARY KEY (id)
);

ALTER TABLE material_eco
    ADD CONSTRAINT uc_material_eco_classe_modelo UNIQUE (classe_modelo);

